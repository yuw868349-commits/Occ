#[test]
fn every_case_matches_the_reference() {
    let dec = AnyDecoder::new(Arch::Aarch64, 64).expect("aarch64 decoder");
    let mut bad = Vec::new();
    for &(word, want) in CASES {
        let bytes = word.to_le_bytes();
        match dec.decode(Addr(0), &bytes) {
            Some(d) => {
                if d.insn.text != want {
                    bad.push((word, want, d.insn.text.clone()));
                }
            }
            None => bad.push((word, want, "<none>".to_string())),
        }
    }
    for (word, want, got) in &bad {
        eprintln!("{word:08x}\n  want {want:?}\n  got  {got:?}");
    }
    assert!(bad.is_empty(), "{} of {} cases differ", bad.len(), CASES.len());
}
