//! The vector opcode tables.
//!
//! Every entry was produced by building the encoding and asking two
//! independent disassemblers what they mean, rather than by writing the
//! names down from memory. The scripts that do this are
//! `scripts/vector_tables.py` and `scripts/evex_tables.py`.
//!
//! The table has one row for every combination of the opcode byte and the
//! mandatory prefix, because that is the granularity at which the
//! instruction is named: the `0f` map's `0x10` is four different
//! instructions — `vmovups`, `vmovupd`, `vmovss` and `vmovsd` — and each
//! of them has its own operand shape and its own conditions on the rest
//! of the prefix.
//!
//! The rows record three things about an instruction: its name, the shape
//! of its operands, and the size of its memory operand. The last of the
//! three cannot be read off the register form, so the broadcasts and the
//! moves between a vector and a general-purpose register are listed by
//! hand.

